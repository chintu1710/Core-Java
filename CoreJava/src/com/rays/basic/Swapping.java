package com.rays.basic;

public class Swapping {
	public static void main(String[] args) {
		int a = 10;
		int b = 5;
		int c;
		System.out.println("Before sawpping....");
		System.out.println("a = " + a);
		System.out.println("b = " + b);

		c = a;
		a = b;
		b = c;
		System.out.println("After sawpping....");
		System.out.println("a = " + a);
		System.out.println("b = " + b);

	}

}
