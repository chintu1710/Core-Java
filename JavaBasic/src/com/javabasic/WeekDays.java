package com.javabasic;

public class WeekDays {
	public static void main(String[] args) {

		String Day = "Sun";

		switch (Day) {
		case "Monday":
			System.out.println("Weeak of first day ");
			break;
		case "Tuesday":
			System.out.println("Weeak of Second day");
			break;
		case "Wenesday":
			System.out.println("Weeak of third day");
			break;
		case "Thusday":
			System.out.println("Weeak of Fourth day");
			break;
		case "Friday":
			System.out.println("Weeak of fifth day ");
			break;
		case "Saturday":
			System.out.println("Weeak of Sixth day");
			break;
		default:
			System.out.println("happy sunday");
			break;
		}

	}

}
